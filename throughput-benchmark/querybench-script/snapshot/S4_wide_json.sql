-- Fat-JSON decode over a 30-minute slice of the closed partition.
--
-- STEP 4 OF 4, SNAPSHOT SUITE, AND THE ONLY WINDOWED ONE. This is the
-- expensive query: it decodes event_json (~3.3 KB/row, ~82% of the table's
-- bytes) at partition scale, which is where compaction state and fat-column
-- decode cost compound and where H5's 5-minute hot window cannot reach.
--
-- ── WHY THIS ONE CARRIES A WINDOW AND S1-S3 DO NOT ──────────────────────────
-- S4 is what made this suite a multi-hour run. Measured per pass per arm: 18-41
-- min on StarRocks, 25.7 min on DuckDB, and in the cancelled 2026-10-06 run it
-- passed 1,513 s on arm one alone with a ~12 h projection for the full matrix.
--
-- The retired uuid modulo sample could not fix that, because uuid is random and
-- so prunes NOTHING — the decode happens during the scan, before the filter.
-- ingestionTime DOES prune: it is monotonic with write order, so its row-group
-- min/max are tight and whole files are skipped. That is the entire reason the
-- bound differs between S1-S3 and S4 rather than being uniform.
--
-- ── THE WINDOW IS ON THE INGESTION DATE, NOT THE PARTITION DATE ─────────────
-- ${S4_FROM}/${S4_TO} are NOT inside dt=${SNAPSHOT_DT}, and that is correct. dt
-- derives from eventTimeDT = event_ts - r_day days
-- (sql-scripts/common/01-datagen-source.sql:592, cut to dt at :607) while
-- ingestionTime is the wall clock at write (:657). So dt=2026-10-04 was WRITTEN
-- on 2026-10-05 — verified on all three arms, whose MAX(ingestionTime) for that
-- partition were 2026-10-05 04:40:58 / 04:35:17 / 04:46:01.
--
-- Anchoring the window to ${SNAPSHOT_DT} itself matches ZERO rows and returns
-- instantly. That reads as a spectacular win and measures nothing — the same
-- silent, flattering failure as a stale pinned dt. SNAPSHOT_INGEST_DATE
-- defaults to SNAPSHOT_DT + 1 day for this reason; override it if the
-- generator's day spread changes.
--
-- Half-open [FROM, TO), so adjacent windows neither overlap nor gap.
--
-- ── IF THIS OOMs, enable_spill IS THE WRONG LEVER ───────────────────────────
-- On StarRocks the failure names `read and decompress page` / `get chunk from
-- scanner`, i.e. it is SCAN-side. Spill covers aggregate, sort and join
-- operators only and structurally cannot reach it. The fix is BOTH
--   SET connector_io_tasks_per_scan_operator = 2;
--   SET enable_connector_adaptive_io_tasks = false;
-- The second is not optional: without it the adaptive scheduler raises the task
-- count back up at runtime and the first has no effect.
--
-- payload_bytes is the cross-engine equality check; ${BYTES_FN} is LENGTH on
-- StarRocks and STRLEN on DuckDB. See H5_hot_wide_json.sql for why that
-- substitution exists rather than a hardcoded name.
--
-- ── IT SUBSUMES starrocks-bench.sh's q5_wide_scan ──────────────────────────
-- q5 was `SELECT COUNT(*), SUM(LENGTH(event_json)) FROM cid_events` — this
-- query with no bound at all, and its own header called it "by far the
-- longest". That is the same query this file's window exists to make
-- survivable: bounded to ONE partition it already runs 18-41 min per pass per
-- arm, so unbounded across ~8 TiB it is a multi-hour single statement that
-- QUERY_TIMEOUT kills. The bound costs nothing analytically, because the
-- fat-column tax is a per-byte rate: read it as H5/H4 and S4/S1 ratios, which
-- is what makes it comparable across arms regardless of how many bytes each
-- one held.
--
-- LENGTH is replaced by ${BYTES_FN}, which is the one change q5 could not have
-- made on its own — it was StarRocks-only, so a hardcoded LENGTH was correct
-- there and silently counts CHARACTERS on DuckDB.
SELECT COUNT(*)                     AS n,
       SUM(${BYTES_FN}(event_json)) AS payload_bytes
FROM ${TABLE}
WHERE dt = '${SNAPSHOT_DT}'
  AND ingestionTime >= '${S4_FROM}'
  AND ingestionTime <  '${S4_TO}';
